-- Migration 034: Bảng giá thuốc có hiệu lực + lịch sử (Issue #865 / S3a, BF-03 §4 CL-4).
--
-- Owner decision D1: giá tính THEO THUỐC (medicines.id), KHÔNG theo lô (medicine_batches).
-- A medicine may have many price rows over time; exactly one row is effective at any instant
-- (half-open interval [effective_from, effective_to), NULL effective_to = còn hiệu lực).
--
-- Shape replicates service_prices (migration 021 / AdminServicePricesController) with the
-- medicine scope and the admin audit columns added by owner scope:
--   * hospital_id is denormalized so a price row can never drift outside the medicine's
--     hospital scope; the application verifies medicines.hospital_id = medicine_prices.hospital_id.
--   * decision_number / applied_by / note are durable price-decision metadata (the same values
--     also go into audit_logs as MEDICINE_PRICE_UPDATED change data).
--   * created_at / created_by_user_id record who set the price.
--
-- Overlap policy: replicated from ServicePrice — enforced in the application inside a
-- transaction that locks the parent medicine row FOR UPDATE (TryLockMedicineForUpdateAsync).
-- No PostgreSQL EXCLUDE constraint is used because it would require the btree_gist extension
-- and would reject the legitimate split/resume algorithm (close baseline at the new start,
-- resume the old amount at the new end).
--
-- Idempotent: guarded CREATE TABLE / ADD CONSTRAINT / CREATE INDEX; safe to re-run.
-- ROLLBACK: DROP TABLE IF EXISTS "medicine_prices";

BEGIN;

SET LOCAL lock_timeout = '10s';

-- ============================================================================
-- 1. medicine_prices
-- ============================================================================
CREATE TABLE IF NOT EXISTS "medicine_prices" (
  "id" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "hospital_id" bigint NOT NULL REFERENCES "hospitals" ("id") ON DELETE RESTRICT,
  "medicine_id" bigint NOT NULL REFERENCES "medicines" ("id") ON DELETE RESTRICT,
  "price_amount" numeric(14,2) NOT NULL,
  "effective_from" timestamp without time zone NOT NULL,
  "effective_to" timestamp without time zone NULL,
  "decision_number" varchar(100) NULL,
  "applied_by" varchar(150) NULL,
  "note" varchar(500) NULL,
  "created_at" timestamp without time zone NOT NULL DEFAULT now(),
  "created_by_user_id" bigint NULL REFERENCES "users" ("id") ON DELETE SET NULL
);

-- 1.1. Check constraints (idempotent for databases that already ran an earlier 034 shape).
DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'chk_medicine_prices_price_amount_nonnegative'
                   AND conrelid = '"medicine_prices"'::regclass) THEN
    ALTER TABLE "medicine_prices"
      ADD CONSTRAINT "chk_medicine_prices_price_amount_nonnegative"
      CHECK ("price_amount" >= 0);
  END IF;

  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'chk_medicine_prices_effective_range'
                   AND conrelid = '"medicine_prices"'::regclass) THEN
    ALTER TABLE "medicine_prices"
      ADD CONSTRAINT "chk_medicine_prices_effective_range"
      CHECK ("effective_to" IS NULL OR "effective_to" > "effective_from");
  END IF;
END $$;

-- ============================================================================
-- 2. Indexes
-- ============================================================================
-- Effective-price lookup: medicine + newest-first effective windows (#866 resolver).
CREATE INDEX IF NOT EXISTS "ix_medicine_prices_effective_lookup"
  ON "medicine_prices" ("medicine_id", "effective_from" DESC);

-- Hospital-scoped admin list / authorization filtering.
CREATE INDEX IF NOT EXISTS "ix_medicine_prices_hospital_id"
  ON "medicine_prices" ("hospital_id");

-- ============================================================================
-- 3. Owner-decision guard: prices are medicine-scoped, never batch-scoped.
--    No migration touches medicine_batches.
-- ============================================================================

COMMIT;

