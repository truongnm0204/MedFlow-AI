BEGIN;

SET LOCAL lock_timeout = '10s';

-- ============================================================================
-- 1. diagnostic_order_routing_history
-- ============================================================================
CREATE TABLE IF NOT EXISTS "diagnostic_order_routing_history" (
  "id" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "diagnostic_order_id" bigint NOT NULL REFERENCES "diagnostic_orders" ("id") ON DELETE CASCADE,
  "visit_id" bigint NULL REFERENCES "visits" ("id") ON DELETE SET NULL,
  "hospital_id" bigint NULL REFERENCES "hospitals" ("id") ON DELETE SET NULL,
  "from_service_point_id" bigint NULL REFERENCES "queue_service_points" ("id") ON DELETE SET NULL,
  "to_service_point_id" bigint NULL REFERENCES "queue_service_points" ("id") ON DELETE SET NULL,
  "source" varchar(32) NOT NULL,
  "reason" text NULL,
  "changed_by_user_id" bigint NULL REFERENCES "users" ("id") ON DELETE SET NULL,
  "changed_by_role" varchar(32) NULL,
  "created_at" timestamp without time zone NOT NULL DEFAULT now()
);

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
    WHERE conname = 'chk_diagnostic_order_routing_history_source'
      AND conrelid = '"diagnostic_order_routing_history"'::regclass)
  THEN
    ALTER TABLE "diagnostic_order_routing_history"
      ADD CONSTRAINT "chk_diagnostic_order_routing_history_source"
      CHECK ("source" IN ('AUTO_ROUTING', 'MANUAL_REASSIGN', 'RECEIVE_REROUTE'));
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
    WHERE conname = 'chk_diagnostic_order_routing_history_target'
      AND conrelid = '"diagnostic_order_routing_history"'::regclass)
  THEN
    ALTER TABLE "diagnostic_order_routing_history"
      ADD CONSTRAINT "chk_diagnostic_order_routing_history_target"
      CHECK ("to_service_point_id" IS NOT NULL);
  END IF;
END $$;

CREATE INDEX IF NOT EXISTS "ix_diagnostic_order_routing_history_order"
  ON "diagnostic_order_routing_history" ("diagnostic_order_id", "created_at" DESC);

CREATE INDEX IF NOT EXISTS "ix_diagnostic_order_routing_history_visit"
  ON "diagnostic_order_routing_history" ("visit_id", "created_at" DESC);

-- ============================================================================
-- 2. Quyền điều phối lại riêng cho Staff CLS + Reception
-- ============================================================================
INSERT INTO "permissions" ("code")
SELECT 'DIAGNOSTIC_REROUTE'
WHERE NOT EXISTS (SELECT 1 FROM "permissions" WHERE "code" = 'DIAGNOSTIC_REROUTE');

INSERT INTO "role_permissions" ("role_id", "permission_id")
SELECT r."id", p."id"
FROM "roles" r
CROSS JOIN "permissions" p
WHERE p."code" = 'DIAGNOSTIC_REROUTE'
  AND r."code" IN ('DIAGNOSTIC_STAFF', 'RECEPTION')
ON CONFLICT DO NOTHING;

COMMIT;
