BEGIN;

CREATE TABLE IF NOT EXISTS patient_identity_claims (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  requester_user_id BIGINT NOT NULL REFERENCES users (id),
  current_patient_id BIGINT NULL REFERENCES patients (id),
  target_patient_id BIGINT NULL REFERENCES patients (id),
  requested_patient_code VARCHAR(40) NOT NULL,
  hospital_id BIGINT NOT NULL REFERENCES hospitals (id),
  status VARCHAR(24) NOT NULL,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
  expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
  decided_at TIMESTAMP WITH TIME ZONE NULL,
  decided_by_staff_id BIGINT NULL REFERENCES staff (id),
  decision_note VARCHAR(500) NULL
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_identity_claims_open_user
  ON patient_identity_claims (requester_user_id)
  WHERE status IN ('PENDING', 'NEEDS_RECONCILIATION');

CREATE INDEX IF NOT EXISTS ix_identity_claims_target_status
  ON patient_identity_claims (target_patient_id, status);

CREATE INDEX IF NOT EXISTS ix_identity_claims_status_expires
  ON patient_identity_claims (status, expires_at);

CREATE INDEX IF NOT EXISTS ix_identity_claims_hospital_status
  ON patient_identity_claims (hospital_id, status);

COMMIT;
