--
-- Idempotent: guarded CREATE TABLE / ADD COLUMN / CREATE INDEX.
-- ROLLBACK:
--   DROP TABLE IF EXISTS "diagnostic_order_declines";
--   DROP INDEX IF EXISTS "ix_notifications_recipient_user_id";
--   ALTER TABLE "notifications" DROP COLUMN IF EXISTS "recipient_user_id";

BEGIN;

SET LOCAL lock_timeout = '10s';

-- ============================================================================
-- 1. diagnostic_order_declines
-- ============================================================================
CREATE TABLE IF NOT EXISTS "diagnostic_order_declines" (
  "id" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "diagnostic_order_id" bigint NOT NULL REFERENCES "diagnostic_orders" ("id") ON DELETE CASCADE,
  "visit_id" bigint NOT NULL REFERENCES "visits" ("id") ON DELETE CASCADE,
  "hospital_id" bigint NULL REFERENCES "hospitals" ("id") ON DELETE SET NULL,
  "recorded_by_user_id" bigint NOT NULL REFERENCES "users" ("id") ON DELETE RESTRICT,
  "recorded_by_role" varchar(32) NOT NULL,
  "source" varchar(16) NOT NULL,
  "reason" text NOT NULL,
  "notified_doctor_id" bigint NULL REFERENCES "doctors" ("id") ON DELETE SET NULL,
  "notified_doctor_user_id" bigint NULL REFERENCES "users" ("id") ON DELETE SET NULL,
  "created_at" timestamp without time zone NOT NULL DEFAULT now()
);

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
    WHERE conname = 'chk_diagnostic_order_declines_source'
      AND conrelid = '"diagnostic_order_declines"'::regclass)
  THEN
    ALTER TABLE "diagnostic_order_declines"
      ADD CONSTRAINT "chk_diagnostic_order_declines_source"
      CHECK ("source" IN ('PATIENT', 'RECEPTION', 'DOCTOR'));
  END IF;
END $$;

CREATE INDEX IF NOT EXISTS "ix_diagnostic_order_declines_order"
  ON "diagnostic_order_declines" ("diagnostic_order_id", "created_at" DESC);

CREATE INDEX IF NOT EXISTS "ix_diagnostic_order_declines_visit"
  ON "diagnostic_order_declines" ("visit_id", "created_at" DESC);

-- ============================================================================
-- 2. notifications.recipient_user_id (thông báo in-app cho bác sĩ điều trị)
-- ============================================================================
ALTER TABLE "notifications" ADD COLUMN IF NOT EXISTS "recipient_user_id" bigint NULL;

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
    WHERE conname = 'fk_notifications_recipient_user_id'
      AND conrelid = '"notifications"'::regclass)
  THEN
    ALTER TABLE "notifications"
      ADD CONSTRAINT "fk_notifications_recipient_user_id"
      FOREIGN KEY ("recipient_user_id") REFERENCES "users" ("id")
      ON DELETE SET NULL;
  END IF;
END $$;

CREATE INDEX IF NOT EXISTS "ix_notifications_recipient_user_id"
  ON "notifications" ("recipient_user_id", "created_at" DESC)
  WHERE "recipient_user_id" IS NOT NULL;

COMMIT;
