-- Migration 030: eKYC proxy call logs (Phase 1 slice 2 — transparent proxy metadata).
--
-- Adds ONE table "ekyc_proxy_call_logs" — per-call metadata for every request the
-- backend proxies to VNPT on behalf of an eKYC session. Exists for:
--   1. Finalize audit (slice 3): which endpoints were hit, in what order, with what
--      object-hash refs — evidence for step-binding verification.
--   2. Binding validation: which object hashes were uploaded under this session
--      (addFile object.hash) vs which hash the face/compare call referenced.
--   3. e2e debug signal: parse failures when VNPT/SDK shape diverges from assumptions.
--
-- HARD RULE: metadata only — NEVER images, NEVER base64 payloads, NEVER OCR text.
-- Only endpoint paths, status codes, object-hash references and JSON fingerprints.
--
-- Also adds binding-validation columns on ekyc_verification_sessions:
--   binding_state      — PENDING / NOT_APPLICABLE / VALID / INVALID_BINDING / UNVERIFIABLE_BINDING
--                        (fail-closed; NOT_APPLICABLE = optional face-compare step not run)
--   compare_reference_hash — the document hash the compare call referenced (first observed)
-- Stores hashes (hex/base64 refs), not images.
--
-- 100% idempotent. Never edits rows of other tables.

BEGIN;

SET LOCAL lock_timeout = '10s';

-- ============================================================================
-- 0. FAIL-FAST PREFLIGHT (re-run consistency)
-- ============================================================================
DO $$
DECLARE
  v_bad_count bigint := 0;
  v_samples text := '';
BEGIN
  IF to_regclass('public.ekyc_proxy_call_logs') IS NOT NULL THEN
    EXECUTE $dyn$
      SELECT COUNT(*), coalesce(string_agg(id::text, ', ' ORDER BY id), '')
      FROM (
        SELECT l.id
        FROM ekyc_proxy_call_logs l
        LEFT JOIN ekyc_verification_sessions s ON s.id = l.session_id
        WHERE s.id IS NULL
           OR l.http_status < 100 OR l.http_status > 599
        ORDER BY l.id
        LIMIT 10
      ) v
    $dyn$ INTO v_bad_count, v_samples;

    IF v_bad_count > 0 THEN
      RAISE EXCEPTION '[PREFLIGHT_030_FAILED] ekyc_proxy_call_logs has orphan rows or invalid http_status (% row(s); sample ids: %). Run database/scripts/preflight_030_audit.sql.',
        v_bad_count, v_samples;
    END IF;
  END IF;
END $$;

-- ============================================================================
-- 1. ekyc_proxy_call_logs
-- ============================================================================
CREATE TABLE IF NOT EXISTS "ekyc_proxy_call_logs" (
  "id" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "session_id" bigint NOT NULL REFERENCES "ekyc_verification_sessions" ("id") ON DELETE RESTRICT,
  -- VNPT endpoint path relative to backend_url, e.g. /ai/v1/web/ocr/id/front. Never a full URL with query secrets.
  "endpoint_path" varchar(256) NOT NULL,
  -- HTTP method as forwarded (POST for all known VNPT inference endpoints).
  "http_method" varchar(8) NOT NULL,
  "http_status" integer NOT NULL,
  -- Object-hash refs extracted from the REQUEST body (img / img_front / img_back).
  -- Shape reference, not image content. NULL when endpoint carries no hash refs.
  "request_object_hashes" jsonb NULL,
  -- object.hash extracted from an addFile RESPONSE (server-issued upload ref).
  "response_object_hash" varchar(256) NULL,
  -- Set when request/response body JSON could not be parsed or shape diverged from assumption —
  -- short machine-readable reason (e.g. 'malformed_json', 'missing_hash_field'). Debug signal only.
  "parse_warning" varchar(128) NULL,
  -- Response duration in milliseconds (upstream latency observability).
  "duration_ms" integer NULL,
  "created_at" timestamp without time zone NOT NULL DEFAULT now()
);

DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'chk_ekyc_log_http_status'
                   AND conrelid = '"ekyc_proxy_call_logs"'::regclass) THEN
    ALTER TABLE "ekyc_proxy_call_logs"
      ADD CONSTRAINT "chk_ekyc_log_http_status"
      CHECK ("http_status" >= 100 AND "http_status" <= 599);
  END IF;
END $$;

-- ============================================================================
-- 2. Indexes
-- ============================================================================
-- Finalize reconstruction: all calls of one session in order.
CREATE INDEX IF NOT EXISTS "ix_ekyc_logs_session_created"
  ON "ekyc_proxy_call_logs" ("session_id", "created_at");

-- Hash-ref lookup: which sessions uploaded/referenced a given object hash.
CREATE INDEX IF NOT EXISTS "ix_ekyc_logs_response_object_hash"
  ON "ekyc_proxy_call_logs" ("response_object_hash")
  WHERE "response_object_hash" IS NOT NULL;

-- ============================================================================
-- 3. Binding-validation columns on ekyc_verification_sessions
-- ============================================================================
ALTER TABLE "ekyc_verification_sessions"
  ADD COLUMN IF NOT EXISTS "binding_state" varchar(32) NOT NULL DEFAULT 'PENDING',
  ADD COLUMN IF NOT EXISTS "compare_reference_hash" varchar(256) NULL;

DO $$
BEGIN
  -- Recreate when the earlier unmerged constraint predates NOT_APPLICABLE (owner scope
  -- 2026-11-28: face/compare optional, so "not run" must be representable without failing).
  IF EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'chk_ekyc_binding_state'
               AND conrelid = '"ekyc_verification_sessions"'::regclass
               AND pg_get_constraintdef(oid) NOT LIKE '%NOT_APPLICABLE%') THEN
    ALTER TABLE "ekyc_verification_sessions" DROP CONSTRAINT "chk_ekyc_binding_state";
  END IF;

  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'chk_ekyc_binding_state'
                   AND conrelid = '"ekyc_verification_sessions"'::regclass) THEN
    ALTER TABLE "ekyc_verification_sessions"
      ADD CONSTRAINT "chk_ekyc_binding_state"
      CHECK ("binding_state" IN ('PENDING','NOT_APPLICABLE','VALID','INVALID_BINDING','UNVERIFIABLE_BINDING'));
  END IF;
END $$;

COMMIT;
