BEGIN;

CREATE TABLE IF NOT EXISTS payment_gateway_events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  provider VARCHAR(20) NOT NULL,
  external_id VARCHAR(80) NOT NULL,
  payment_id BIGINT NULL REFERENCES payments (id),
  payment_code VARCHAR(40) NULL,
  transfer_amount NUMERIC(16,2) NULL,
  reference_code VARCHAR(150) NULL,
  outcome VARCHAR(24) NOT NULL,
  received_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX IF NOT EXISTS ux_payment_gateway_events_provider_external
  ON payment_gateway_events (provider, external_id);

CREATE INDEX IF NOT EXISTS ix_payment_gateway_events_payment_id
  ON payment_gateway_events (payment_id);

CREATE INDEX IF NOT EXISTS ix_payment_gateway_events_payment_code
  ON payment_gateway_events (payment_code);

COMMIT;
