-- Migration 036: Cấu hình nhóm chuyên môn / nhịn đói / phụ thuộc CLS + gán điểm & thứ tự
-- cho chỉ định cận lâm sàng (#869 / S5a, owner chốt 29/11).
--
-- Owner decision:
--   * Thứ tự CLS: nhịn đói trước -> xét nghiệm máu -> chẩn đoán hình ảnh -> thăm dò chức năng;
--     cùng nhóm thì điểm ít người đang chờ trước.
--   * Hệ thống ĐỀ XUẤT thứ tự; nhân viên chỉ đổi khi có lý do hợp lệ và không vi phạm điều kiện chuyên môn.
--   * Gán điểm ngay khi tạo chỉ định để in phiếu; tải điểm = SỐ NGƯỜI ĐANG CHỜ (D3).
--
-- Shape:
--   * services.diagnostic_group: BLOOD_TEST | IMAGING | FUNCTIONAL (cấu hình theo dịch vụ CLS).
--   * services.requires_fasting: cờ nhịn đói theo dịch vụ CLS.
--   * diagnostic_service_dependencies: điều kiện phụ thuộc chuyên môn giữa hai dịch vụ CLS
--     (service phải thực hiện SAU prerequisite trong cùng lượt khám).
--   * diagnostic_orders.assigned_service_point_id + sequence_no: điểm được phân công và thứ tự CLS
--     đề xuất, gán ngay khi bác sĩ tạo chỉ định.
--
-- Idempotent: guarded ADD COLUMN / CREATE TABLE / ADD CONSTRAINT / CREATE INDEX; safe to re-run.
-- ROLLBACK:
--   ALTER TABLE "diagnostic_orders" DROP COLUMN IF EXISTS "sequence_no";
--   ALTER TABLE "diagnostic_orders" DROP COLUMN IF EXISTS "assigned_service_point_id";
--   DROP TABLE IF EXISTS "diagnostic_service_dependencies";
--   ALTER TABLE "services" DROP COLUMN IF EXISTS "requires_fasting";
--   ALTER TABLE "services" DROP COLUMN IF EXISTS "diagnostic_group";

BEGIN;

SET LOCAL lock_timeout = '10s';

-- ============================================================================
-- 1. services: nhóm chuyên môn CLS + cờ nhịn đói
-- ============================================================================
ALTER TABLE "services" ADD COLUMN IF NOT EXISTS "diagnostic_group" varchar(32) NULL;
ALTER TABLE "services" ADD COLUMN IF NOT EXISTS "requires_fasting" boolean NOT NULL DEFAULT false;

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
    WHERE conname = 'chk_services_diagnostic_group'
      AND conrelid = '"services"'::regclass)
  THEN
    ALTER TABLE "services"
      ADD CONSTRAINT "chk_services_diagnostic_group"
      CHECK ("diagnostic_group" IS NULL OR "diagnostic_group" IN ('BLOOD_TEST', 'IMAGING', 'FUNCTIONAL'));
  END IF;
END $$;

-- Backfill nhóm chuyên môn cho catalog CLS hiện có (chỉ khi chưa cấu hình).
-- Ưu tiên mã dịch vụ demo (DIA-CBC/DIA-GLU/DIA-HP/DIA-US/DIA-XRAY/DIA-ECG) rồi tới từ khóa tên.
UPDATE "services"
SET "diagnostic_group" = 'BLOOD_TEST'
WHERE "diagnostic_group" IS NULL
  AND upper(coalesce("service_type", '')) = 'DIAGNOSTIC'
  AND (
    upper(coalesce("service_code", '')) IN ('DIA-CBC', 'DIA-GLU', 'DIA-HP')
    OR upper(coalesce("name", '')) LIKE '%MÁU%'
    OR upper(coalesce("name", '')) LIKE '%HUYẾT%'
    OR upper(coalesce("name", '')) LIKE '%GLUCOSE%'
    OR upper(coalesce("name", '')) LIKE '%SINH HÓA%'
    OR upper(coalesce("name", '')) LIKE '%NƯỚC TIỂU%'
  );

UPDATE "services"
SET "diagnostic_group" = 'IMAGING'
WHERE "diagnostic_group" IS NULL
  AND upper(coalesce("service_type", '')) = 'DIAGNOSTIC'
  AND (
    upper(coalesce("service_code", '')) IN ('DIA-US', 'DIA-XRAY')
    OR upper(coalesce("name", '')) LIKE '%SIÊU ÂM%'
    OR upper(coalesce("name", '')) LIKE '%X-QUANG%'
    OR upper(coalesce("name", '')) LIKE '%XQUANG%'
    OR upper(coalesce("name", '')) LIKE '%CT %'
    OR upper(coalesce("name", '')) LIKE '%MRI%'
    OR upper(coalesce("name", '')) LIKE '%CHỤP%'
  );

UPDATE "services"
SET "diagnostic_group" = 'FUNCTIONAL'
WHERE "diagnostic_group" IS NULL
  AND upper(coalesce("service_type", '')) = 'DIAGNOSTIC'
  AND (
    upper(coalesce("service_code", '')) = 'DIA-ECG'
    OR upper(coalesce("name", '')) LIKE '%ĐIỆN TÂM ĐỒ%'
    OR upper(coalesce("name", '')) LIKE '%ĐIỆN NÃO ĐỒ%'
    OR upper(coalesce("name", '')) LIKE '%HOLTER%'
    OR upper(coalesce("name", '')) LIKE '%CHỨC NĂNG%'
  );

-- Cờ nhịn đói: glucose/lipid/mỡ máu và siêu âm bụng (an toàn, chỉ bật khi chưa cấu hình tường minh).
UPDATE "services"
SET "requires_fasting" = true
WHERE "requires_fasting" = false
  AND upper(coalesce("service_type", '')) = 'DIAGNOSTIC'
  AND (
    upper(coalesce("service_code", '')) = 'DIA-GLU'
    OR upper(coalesce("name", '')) LIKE '%GLUCOSE%'
    OR upper(coalesce("name", '')) LIKE '%LIPID%'
    OR upper(coalesce("name", '')) LIKE '%MỠ MÁU%'
    OR upper(coalesce("name", '')) LIKE '%SIÊU ÂM BỤNG%'
    OR upper(coalesce("name", '')) LIKE '%SIÊU ÂM Ổ BỤNG%'
  );

-- ============================================================================
-- 2. diagnostic_service_dependencies: điều kiện phụ thuộc chuyên môn theo dịch vụ CLS
-- ============================================================================
CREATE TABLE IF NOT EXISTS "diagnostic_service_dependencies" (
  "id" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "hospital_id" bigint NULL REFERENCES "hospitals" ("id") ON DELETE SET NULL,
  "service_id" bigint NOT NULL REFERENCES "services" ("id") ON DELETE CASCADE,
  "prerequisite_service_id" bigint NOT NULL REFERENCES "services" ("id") ON DELETE CASCADE,
  "note" varchar(500) NULL,
  "created_at" timestamp without time zone NOT NULL DEFAULT now()
);

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
    WHERE conname = 'chk_diagnostic_service_dependencies_not_self'
      AND conrelid = '"diagnostic_service_dependencies"'::regclass)
  THEN
    ALTER TABLE "diagnostic_service_dependencies"
      ADD CONSTRAINT "chk_diagnostic_service_dependencies_not_self"
      CHECK ("service_id" <> "prerequisite_service_id");
  END IF;
END $$;

CREATE UNIQUE INDEX IF NOT EXISTS "uq_diagnostic_service_dependencies_pair"
  ON "diagnostic_service_dependencies" ("service_id", "prerequisite_service_id");

CREATE INDEX IF NOT EXISTS "ix_diagnostic_service_dependencies_prerequisite"
  ON "diagnostic_service_dependencies" ("prerequisite_service_id");

-- ============================================================================
-- 3. diagnostic_orders: điểm được phân công + thứ tự CLS đề xuất
-- ============================================================================
ALTER TABLE "diagnostic_orders"
  ADD COLUMN IF NOT EXISTS "assigned_service_point_id" bigint NULL;

ALTER TABLE "diagnostic_orders"
  ADD COLUMN IF NOT EXISTS "sequence_no" integer NULL;

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
    WHERE conname = 'fk_diagnostic_orders_assigned_service_point_id'
      AND conrelid = '"diagnostic_orders"'::regclass)
  THEN
    ALTER TABLE "diagnostic_orders"
      ADD CONSTRAINT "fk_diagnostic_orders_assigned_service_point_id"
      FOREIGN KEY ("assigned_service_point_id") REFERENCES "queue_service_points" ("id")
      ON DELETE SET NULL;
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
    WHERE conname = 'chk_diagnostic_orders_sequence_no_positive'
      AND conrelid = '"diagnostic_orders"'::regclass)
  THEN
    ALTER TABLE "diagnostic_orders"
      ADD CONSTRAINT "chk_diagnostic_orders_sequence_no_positive"
      CHECK ("sequence_no" IS NULL OR "sequence_no" > 0);
  END IF;
END $$;

-- Slip/màn hình patient đọc theo visit + thứ tự; điều phối lại tra theo điểm.
CREATE INDEX IF NOT EXISTS "ix_diagnostic_orders_visit_sequence"
  ON "diagnostic_orders" ("visit_id", "sequence_no");

CREATE INDEX IF NOT EXISTS "ix_diagnostic_orders_assigned_service_point_id"
  ON "diagnostic_orders" ("assigned_service_point_id");

COMMIT;
