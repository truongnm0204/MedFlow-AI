function computeStats(visits: DiagnosticTrackingVisitDto[]): DiagnosticTrackingStatsDto {
  const totalOrders = visits.reduce((acc, v) => acc + v.totalOrders, 0);
  const signedOrders = visits.reduce((acc, v) => acc + v.signedOrders, 0);
  return {
    totalVisits: visits.length,
    completedVisits: visits.filter((v) => v.trackingStatus === 'COMPLETED').length,
    inProgressVisits: visits.filter((v) => v.trackingStatus === 'IN_PROGRESS').length,
    pendingSignVisits: visits.filter((v) => v.trackingStatus === 'PENDING_SIGN').length,
    totalOrders,
    signedOrders,
    waitingOrders: totalOrders - signedOrders,
  };
}

export function resolveMockDoctorDiagnosticTracking(
  params?: DoctorDiagnosticTrackingQueryParams,
): DoctorDiagnosticTrackingResponseDto {
  const stats = computeStats(DOCTOR_DIAGNOSTIC_TRACKING_VISITS_MOCK);

  const keyword = params?.keyword?.trim().toLowerCase();
  const filtered = DOCTOR_DIAGNOSTIC_TRACKING_VISITS_MOCK.filter((visit) => {
    if (params?.status && visit.trackingStatus !== params.status) {
      return false;
    }
    if (keyword) {
      const orderText = visit.orders.map((o) => `${o.orderCode} ${o.serviceName ?? ''}`).join(' ');
      const haystack = [
        visit.visitCode,
        visit.patientCode ?? '',
        visit.patientName ?? '',
        orderText,
      ]
        .join(' ')
        .toLowerCase();
      if (!haystack.includes(keyword)) {
        return false;
      }
    }
    return true;
  });

  const pageSize = Math.min(Math.max(params?.pageSize ?? 20, 1), 100);
  const page = Math.max(params?.page ?? 1, 1);
  const totalCount = filtered.length;
  const totalPages = Math.ceil(totalCount / pageSize);
  const startIndex = (page - 1) * pageSize;
  const pagedItems = filtered.slice(startIndex, startIndex + pageSize);

  return {
    date: params?.date?.trim() || '2026-11-09',
    hospitalId: 1,
    doctorId: 1,
    doctorCode: 'DOC-001',
    doctorName: 'BS. Trần Minh Khoa',
    generatedAtUtc: new Date().toISOString(),
    stats,
    totalCount,
    page,
    pageSize,
    totalPages,
    items: pagedItems,
  };
}
