export function resolveMockDiagnosticWorklist(
  params?: DiagnosticWorklistQueryParams,
): DiagnosticWorklistResponseDto {
  const filtered = DIAGNOSTIC_WORKLIST_ITEMS_MOCK.filter((item) => {
    if (params?.category && params.category !== 'ALL' && item.category !== params.category) {
      return false;
    }
    if (params?.status && params.status !== 'ALL' && item.status !== params.status) {
      return false;
    }
    if (
      params?.queueStatus &&
      params.queueStatus !== 'ALL' &&
      item.queueStatus !== params.queueStatus
    ) {
      return false;
    }
    if (
      params?.resultStatus &&
      params.resultStatus !== 'ALL' &&
      item.resultStatus !== params.resultStatus
    ) {
      return false;
    }
    if (params?.priority && params.priority !== 'ALL' && item.priority !== params.priority) {
      return false;
    }
    if (
      params?.servicePointId &&
      params.servicePointId !== 'ALL' &&
      item.formattedServicePointId !== params.servicePointId &&
      String(item.servicePointId ?? '') !== params.servicePointId
    ) {
      return false;
    }
    const targetDate = params?.queueDate?.trim() || params?.orderDate?.trim();
    if (targetDate && item.queueDate !== targetDate) {
      return false;
    }
    if (
      typeof params?.requiredForConclusion === 'boolean' &&
      item.requiredForConclusion !== params.requiredForConclusion
    ) {
      return false;
    }
    const keyword = params?.keyword?.trim().toLowerCase();
    if (keyword) {
      const haystack = [
        item.orderCode,
        item.ticketNo,
        item.patientName,
        item.patientCode,
        item.visitCode,
        item.serviceName,
        item.serviceCode,
        item.room,
        item.orderingDoctor,
        item.reasonForVisit ?? '',
      ]
        .join(' ')
        .toLowerCase();
      if (!haystack.includes(keyword)) {
        return false;
      }
    }
    return true;
  });

  const pageSize = Math.min(Math.max(params?.pageSize ?? 50, 1), 100);
  const page = Math.max(params?.page ?? 1, 1);
  const totalCount = filtered.length;
  const totalPages = Math.max(1, Math.ceil(totalCount / pageSize));
  const safePage = Math.min(page, totalPages);
  const startIndex = (safePage - 1) * pageSize;
  const pagedItems = filtered.slice(startIndex, startIndex + pageSize);

  return {
    ...DIAGNOSTIC_WORKLIST_MOCK,
    effectiveDate: params?.queueDate?.trim() || DIAGNOSTIC_WORKLIST_MOCK.effectiveDate,
    totalCount,
    page: safePage,
    pageSize,
    totalPages,
    items: pagedItems,
    orders: pagedItems,
    queue: pagedItems,
  };
}

export function resolveMockDiagnosticWorklistOrderDetail(
  orderIdOrCode: string,
): DiagnosticWorklistItemDto | null {
  const normalized = orderIdOrCode.trim().replace(/^#+/, '').trim().toLowerCase();
  if (!normalized) {
    return null;
  }

  return (
    DIAGNOSTIC_WORKLIST_ITEMS_MOCK.find((item) => {
      if (item.id.toLowerCase() === normalized) return true;
      if (String(item.orderId) === normalized) return true;
      if (`do-${item.orderId}` === normalized) return true;
      if (item.orderCode.toLowerCase() === normalized) return true;
      if (item.ticketNo.toLowerCase() === normalized) return true;
      if (item.formattedQueueEntryId?.toLowerCase() === normalized) return true;
      if (item.queueEntryId && `q-${item.queueEntryId}` === normalized) return true;
      return false;
    }) ?? null
  );
}
