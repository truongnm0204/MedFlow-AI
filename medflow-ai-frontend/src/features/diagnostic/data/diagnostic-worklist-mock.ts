function computeWorklistStats(items: DiagnosticWorklistItemDto[]): DiagnosticWorklistStatsDto {
  const pendingOrders = items.filter((item) => item.status === 'ORDERED').length;
  const confirmedOrders = items.filter((item) => item.status === 'CONFIRMED').length;
  const inExecution = items.filter((item) => item.status === 'IN_PROGRESS').length;
  const completedOrders = items.filter((item) => item.status === 'COMPLETED').length;
  const cancelledOrders = items.filter((item) => item.status === 'CANCELLED').length;

  return {
    totalOrders: items.length,
    pendingOrders,
    confirmedOrders,
    inQueue: confirmedOrders + inExecution,
    inExecution,
    completedOrders,
    completedToday: completedOrders,
    cancelledOrders,
    urgentOrders: items.filter((item) => item.priority === 'URGENT').length,
    statOrders: items.filter((item) => item.priority === 'STAT').length,
    mandatoryOrders: items.filter((item) => item.requiredForConclusion).length,
    pendingResultVerificationCount: items.filter((item) => item.resultStatus === 'PENDING_VERIFY')
      .length,
    laboratoryCount: items.filter((item) => item.category === 'LABORATORY').length,
    imagingCount: items.filter((item) => item.category === 'IMAGING').length,
    functionalCount: items.filter((item) => item.category === 'FUNCTIONAL').length,
  };
}

